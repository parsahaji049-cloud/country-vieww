// نمایش صفحه جزئیات کشور
// ============================================
document.addEventListener('DOMContentLoaded', function() {
    // گرفتن نام کشور از URL
    const params = new URLSearchParams(window.location.search);
    const countryName = params.get('name');
    
    const loading = document.getElementById('loadingSpinner');
    const content = document.getElementById('countryContent');
    const detailContainer = document.getElementById('detailContainer');
    
    if (!countryName || !countriesData[countryName]) {
        loading.style.display = 'none';
        content.style.display = 'block';
        content.innerHTML = `
            <div class="error-page">
                <span style="font-size: 60px; display: block; margin-bottom: 20px;">😕</span>
                <h2>کشور مورد نظر یافت نشد!</h2>
                <p style="color: #666; margin: 10px 0 20px;">کشور "${countryName}" در لیست ما وجود ندارد.</p>
                <a href="/" class="btn-home">🏠 بازگشت به صفحه اصلی</a>
            </div>
        `;
        return;
    }
    
    const data = countriesData[countryName];
    const flagCode = getFlagCode(countryName);
    
    // مخفی کردن اسپینر و نمایش محتوا
    setTimeout(() => {
        loading.style.display = 'none';
        content.style.display = 'block';
        content.innerHTML = renderCountryDetail(data, flagCode);
    }, 500);
});

